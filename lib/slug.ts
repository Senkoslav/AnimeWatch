import { z } from "zod";

/**
 * Формат slug тайтла: строчная латиница, цифры и одиночные дефисы. Один на всех: страница тайтла отвечает 404
 * на всё, что ему не соответствует, поэтому админка и импорт обязаны проверять slug той же схемой, иначе
 * тайтл заведётся, а открыть его будет нельзя.
 */
export const slugSchema = z
  .string()
  .max(120)
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/);
