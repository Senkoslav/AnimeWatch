#!/usr/bin/env sh
# Сборка на Vercel. Миграции применяются здесь, а не руками: собранный деплой обязан означать
# «работает», а не «скомпилировалось». Без этого шага код, читающий новую колонку, уезжает в прод
# раньше самой колонки, и падает только рантайм — сборка при этом зелёная.
#
# Только для продакшена: превью и прод сейчас смотрят в одну базу Neon (открытый вопрос роадмапа
# «База для превью Vercel»). Безусловный шаг означал бы, что миграция с недоделанной ветки
# применяется к боевой базе раньше, чем туда попадёт её код.
set -e

if [ "$VERCEL_ENV" = "production" ]; then
  echo "Продакшен: применяю миграции"
  pnpm exec prisma migrate deploy
else
  echo "Окружение $VERCEL_ENV: миграции пропущены, база общая с продом"
fi

pnpm exec next build
